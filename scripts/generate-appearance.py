def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", nargs="?", choices=("build", "check"), default="build")
    parser.add_argument("--auth-only", action="store_true", help="Generate login/lock projections only; never touch watched desktop QML")
    args = parser.parse_args()
    def selected(path):
        relative = path.relative_to(ROOT).as_posix()
        return not args.auth_only or relative in {"appearance/shared/auth/VisualRoles.js", "appearance/lock/hyprlock.conf", "appearance/lock/hyprlock-live.conf", "appearance/lock/assets/auth-surface.svg", "appearance/lock/assets/auth-surface.png"} or relative.startswith("appearance/login/sddm/senomyos/")

    tokens = json.loads(TOKENS_PATH.read_text(encoding="utf-8"))
    stale: list[str] = []
    for path, expected in outputs(tokens).items():
        if not selected(path): continue
        if args.mode == "check":
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.new")
        temporary.write_text(expected, encoding="utf-8")
        os.chmod(temporary, 0o644)
        temporary.replace(path)

    for path, expected in binary_outputs(tokens).items():
        if not selected(path): continue
        if args.mode == "check":
            if not path.is_file() or path.read_bytes() != expected:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.new")
        temporary.write_bytes(expected)
        os.chmod(temporary, 0o644)
        temporary.replace(path)

    if stale:
        print("Stale appearance projections:", file=sys.stderr)
        for path in stale:
            print(f"  {path}", file=sys.stderr)
        print("Run ./scripts/generate-appearance.py build", file=sys.stderr)
        return 1
    if args.mode == "build":
        print("SenomyOS appearance projections updated.")
    else:
        print("SenomyOS appearance projections are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
