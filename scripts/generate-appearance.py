def render_frame_module_svg(
    template: str,
    tokens: dict,
    *,
    width: int,
    height: int,
    title: str,
    asset_id: str,
    geometry: str,
    preserve_aspect_ratio: str,
) -> str:
    """Project one fixed or deliberately stretchable standalone SVG module."""
    colors = tokens["frame_system"]["colors"]
    replacements = {
        "@WIDTH@": str(width),
        "@HEIGHT@": str(height),
        "@TITLE@": title,
        "@ASSET_ID@": asset_id,
        "@GEOMETRY@": geometry,
        "@PRESERVE_ASPECT_RATIO@": preserve_aspect_ratio,
        "@IVORY@": colors["ivory"],
        "@COLD_SILVER@": colors["cold_silver"],
        "@STEEL@": colors["steel"],
        "@STRUCTURAL@": colors["structural"],
        "@VIOLET@": colors["violet"],
        "@VIOLET_LIGHT@": colors["violet_light"],
    }
    rendered = template
    for placeholder, value in replacements.items():
        rendered = rendered.replace(placeholder, value)
    if "@" in rendered:
        raise ValueError(f"unresolved placeholder in frame asset {asset_id}")
    return "<!-- Generated by scripts/generate-appearance.py. Do not edit directly. -->\n" + rendered


