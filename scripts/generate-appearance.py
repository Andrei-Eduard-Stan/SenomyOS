def render_hyprlock(template: str, tokens: dict) -> str:
    colors = tokens["colors"]
    replacements = {
        "@BACKGROUND@": rgba(colors["background"], 1.0),
        "@SURFACE@": rgba(colors["surface"], 0.98),
        "@SURFACE_RAISED@": rgba(colors["surface_raised"], 1.0),
        "@FOREGROUND@": rgba(colors["foreground"], 1.0),
        "@MUTED@": rgba(colors["muted"], 1.0),
        "@DIM@": rgba(colors["dim"], 1.0),
        "@ACCENT@": rgba(colors["accent"], 1.0),
        "@WARNING@": rgba(colors["warning"], 1.0),
        "@DANGER@": rgba(colors["danger"], 1.0),
        "@FONT@": tokens["typography"]["family"],
        "@RADIUS@": str(tokens["geometry"]["radius_px"]),
    }
    rendered = template
    for placeholder, value in replacements.items():
        rendered = rendered.replace(placeholder, value)
    if "@" in "".join(line.split("#", 1)[0] for line in rendered.splitlines()):
        raise ValueError("unresolved placeholder in hyprlock template")
    return "# Generated by scripts/generate-appearance.py. Do not edit directly.\n" + rendered


