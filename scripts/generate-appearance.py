def render_svg_png(path: Path) -> bytes:
    try:
        return subprocess.run(
            ("rsvg-convert", "--width", "64", "--height", "64", str(path)),
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        ).stdout
    except FileNotFoundError as error:
        raise RuntimeError("rsvg-convert is required to build Hyprlock PNG icons") from error


def render_svg_text_png(svg: str, width: int, height: int) -> bytes:
    try:
        return subprocess.run(
            ("rsvg-convert", "--width", str(width), "--height", str(height)),
            input=svg.encode("utf-8"),
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        ).stdout
    except FileNotFoundError as error:
        raise RuntimeError("rsvg-convert is required to build SVG raster projections") from error


def render_wallpaper_png(source: Path) -> bytes:
    environment = os.environ.copy()
    environment["SOURCE_DATE_EPOCH"] = "0"
    try:
        return subprocess.run(
            (
                "magick", str(source), "-auto-orient",
                "-resize", "1920x1080^", "-gravity", "center",
                "-extent", "1920x1080", "-strip",
                "-define", "png:exclude-chunks=date,time", "png:-",
            ),
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env=environment,
        ).stdout
    except FileNotFoundError as error:
        raise RuntimeError("ImageMagick is required to build the desktop wallpaper") from error


def blur_wallpaper(png: bytes) -> bytes:
    environment = os.environ.copy()
    environment["SOURCE_DATE_EPOCH"] = "0"
    try:
        return subprocess.run(
            (
                "magick", "png:-", "-strip", "-blur", "0x22",
                "-brightness-contrast", "6x-2",
                "-define", "png:exclude-chunks=date,time", "png:-",
            ),
            input=png,
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env=environment,
        ).stdout
    except FileNotFoundError as error:
        raise RuntimeError("ImageMagick is required to build the blurred login wallpaper") from error


def render_lock_frame_png(
    tokens: dict,
    frame_root: Path,
    *,
    width: int,
    height: int,
    motif: str,
    motif_anchor: str,
) -> bytes:
    """Compose one exact Hyprlock frame from the live Rail's fixed modules."""
    compact = {
        "corner": (16, 16),
        "horizontal_edge_height": 6,
        "vertical_edge_width": 6,
    }
    motif_sizes = {
        "controls": (10, 6),
        "identity": (24, 10),
        "junction": (6, 6),
        "diagnostic-tick": (28, 8),
        "clock-notification": (10, 6),
    }
    corner_width, corner_height = compact["corner"]
    edge_height = compact["horizontal_edge_height"]
    edge_width = compact["vertical_edge_width"]
    motif_width, motif_height = motif_sizes[motif]
    motif_y = 0 if motif_anchor == "top" else height - motif_height

    surface_red, surface_green, surface_blue = rgb(tokens["colors"]["surface_raised"])
    background_red, background_green, background_blue = rgb(tokens["colors"]["background"])
    gradient = (
        f"gradient:rgba({surface_red},{surface_green},{surface_blue},0.72)-"
        f"rgba({background_red},{background_green},{background_blue},0.52)"
    )
    placements = (
        (frame_root / "compact" / "corner-tl.svg", corner_width, corner_height, 0, 0),
        (frame_root / "compact" / "corner-tr.svg", corner_width, corner_height, width - corner_width, 0),
        (frame_root / "compact" / "corner-bl.svg", corner_width, corner_height, 0, height - corner_height),
        (frame_root / "compact" / "corner-br.svg", corner_width, corner_height, width - corner_width, height - corner_height),
        (frame_root / "compact" / "edge-top.svg", width - (corner_width * 2), edge_height, corner_width, 0),
        (frame_root / "compact" / "edge-bottom.svg", width - (corner_width * 2), edge_height, corner_width, height - edge_height),
        (frame_root / "compact" / "edge-left.svg", edge_width, height - (corner_height * 2), 0, corner_height),
        (frame_root / "compact" / "edge-right.svg", edge_width, height - (corner_height * 2), width - edge_width, corner_height),
        (frame_root / "motifs" / f"{motif}.svg", motif_width, motif_height, (width - motif_width) // 2, motif_y),
    )

    command = [
        "magick",
        "(",
        "-size", f"{width}x{height}",
        "-define", "gradient:angle=105",
        gradient,
        ")",
        "(",
        "-size", f"{width}x{height}",
        "xc:none",
        "-fill", "white",
        "-draw", f"roundrectangle 0,0,{width - 1},{height - 1},16,16",
        ")",
        "-alpha", "off",
        "-compose", "CopyOpacity",
        "-composite",
    ]
    for source, item_width, item_height, x, y in placements:
        command.extend(
            (
                "(", str(source), "-background", "none",
                "-resize", f"{item_width}x{item_height}!", ")",
                "-compose", "over", "-geometry", f"+{x}+{y}", "-composite",
            )
        )
    command.extend(("-strip", "-define", "png:exclude-chunks=date,time", "png:-"))

    environment = os.environ.copy()
    environment["SOURCE_DATE_EPOCH"] = "0"
    try:
        return subprocess.run(
            command,
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env=environment,
        ).stdout
    except FileNotFoundError as error:
        raise RuntimeError("ImageMagick is required to build Hyprlock frame projections") from error


def binary_outputs(tokens: dict) -> dict[Path, bytes]:
    shared = ROOT / "appearance" / "shared"
    wallpaper_png = render_wallpaper_png(
        shared / "backgrounds" / "cathedral-reliquary-v1.png"
    )
    wallpaper_blurred = blur_wallpaper(wallpaper_png)
    brand_mark_svg = render_brand_mark_svg(
        (ROOT / "appearance" / "shared" / "brand" / "senomyos-mark.svg.in").read_text(encoding="utf-8"),
        tokens,
    )
    brand_mark_64 = render_svg_text_png(brand_mark_svg, 64, 64)
    brand_mark_128 = render_svg_text_png(brand_mark_svg, 128, 128)
    brand_mark_256 = render_svg_text_png(brand_mark_svg, 256, 256)
    outputs = {
        shared / "backgrounds" / "desktop.png": wallpaper_png,
        shared / "backgrounds" / "desktop-blurred.png": wallpaper_blurred,
        ROOT / "appearance" / "login" / "sddm" / "senomyos" / "assets" / "background.png": wallpaper_blurred,
        ROOT / "appearance" / "login" / "sddm" / "senomyos" / "assets" / "avatar.png": (
            shared / "avatar.png"
        ).read_bytes(),
        ROOT / "appearance" / "shared" / "brand" / "senomyos-mark-64.png": brand_mark_64,
        ROOT / "appearance" / "shared" / "brand" / "senomyos-mark-128.png": brand_mark_128,
        ROOT / "appearance" / "shared" / "brand" / "senomyos-mark-256.png": brand_mark_256,
        # Compatibility projection retained for the existing GRUB/Plymouth
        # manifests and their already-issued rollback receipts.
        ROOT / "appearance" / "boot" / "assets" / "senomyos-mark.png": brand_mark_256,
    }
    sddm_icons = ROOT / "appearance" / "login" / "sddm" / "senomyos" / "assets" / "icons"
    lock_icons = ROOT / "appearance" / "lock" / "assets" / "icons"
    for name in ("accessibility", "keyboard", "next", "power", "recovery", "restart", "session"):
        outputs[lock_icons / f"{name}.png"] = render_svg_png(sddm_icons / f"{name}.svg")
    lock_frames = ROOT / "appearance" / "lock" / "assets" / "frames"
    frame_root = ROOT / "appearance" / "shared" / "frames" / "generated"
    for name, width, motif, motif_anchor in (
        ("utility", 408, "controls", "top"),
        ("identity", 284, "identity", "top"),
        ("authentication", 654, "junction", "top"),
        ("session", 202, "diagnostic-tick", "bottom"),
        ("clock", 220, "clock-notification", "bottom"),
    ):
        outputs[lock_frames / f"{name}.png"] = render_lock_frame_png(
            tokens,
            frame_root,
            width=width,
            height=170,
            motif=motif,
            motif_anchor=motif_anchor,
        )
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", nargs="?", choices=("build", "check"), default="build")
    args = parser.parse_args()

    tokens = json.loads(TOKENS_PATH.read_text(encoding="utf-8"))
    stale: list[str] = []
    for path, expected in outputs(tokens).items():
        if args.mode == "check":
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.new")
        temporary.write_text(expected, encoding="utf-8")
        os.chmod(temporary, 0o644)
        temporary.replace(path)

    for path, expected in binary_outputs(tokens).items():
        if args.mode == "check":
            if not path.is_file() or path.read_bytes() != expected:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.new")
        temporary.write_bytes(expected)
        os.chmod(temporary, 0o644)
        temporary.replace(path)

    if stale:
        print("Stale appearance projections:", file=sys.stderr)
        for path in stale:
            print(f"  {path}", file=sys.stderr)
        print("Run ./scripts/generate-appearance.py build", file=sys.stderr)
        return 1
    if args.mode == "build":
        print("SenomyOS appearance projections updated.")
    else:
        print("SenomyOS appearance projections are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
