def render_frame_module_svg(
    template: str,
    tokens: dict,
    *,
    width: int,
    height: int,
    title: str,
    asset_id: str,
    geometry: str,
    preserve_aspect_ratio: str,
) -> str:
    """Project one fixed or deliberately stretchable standalone SVG module."""
    colors = tokens["frame_system"]["colors"]
    replacements = {
        "@WIDTH@": str(width),
        "@HEIGHT@": str(height),
        "@TITLE@": title,
        "@ASSET_ID@": asset_id,
        "@GEOMETRY@": geometry,
        "@PRESERVE_ASPECT_RATIO@": preserve_aspect_ratio,
        "@IVORY@": colors["ivory"],
        "@COLD_SILVER@": colors["cold_silver"],
        "@STEEL@": colors["steel"],
        "@STRUCTURAL@": colors["structural"],
        "@VIOLET@": colors["violet"],
        "@VIOLET_LIGHT@": colors["violet_light"],
    }
    rendered = template
    for placeholder, value in replacements.items():
        rendered = rendered.replace(placeholder, value)
    if "@" in rendered:
        raise ValueError(f"unresolved placeholder in frame asset {asset_id}")
    return "<!-- Generated by scripts/generate-appearance.py. Do not edit directly. -->\n" + rendered


def render_auth_frame(tokens: dict) -> str:
    """Reuse the authored utility perimeter; never trace replacement corners."""
    auth = tokens["authentication"]
    width, height = auth["lock_panel_width_px"], auth["lock_panel_height_px"]
    palette = tokens["frame_system"]["colors"]
    values = {"WIDTH": width, "HEIGHT": height, "CUTRIGHT": width-12,
              "CUTBOTTOM": height-12, "RIGHT": width-24, "BOTTOM": height-24,
              "BOTTOMRULE": height-2.12, "RIGHTRULE": width-2.08,
              "IVORY": palette["ivory"], "SILVER": palette["cold_silver"],
              "STEEL": palette["steel"], "VIOLET": palette["violet"],
              "FILL": tokens["colors"]["surface"], "ALPHA": 0.98}
    text = (ROOT / "appearance/shared/utility-frame.svg.in").read_text()
    for key, value in values.items(): text = text.replace("@" + key + "@", str(value))
    if "@" in text: raise ValueError("Unresolved authentication frame token")
    return text


